# Rscript test/R/run-hchs-live-tests.R <isolated corrected package library>
# Runs actual installed R and C++ code; never overlays the RNG bridge.
args <- commandArgs(TRUE)
if(length(args)) .libPaths(c(normalizePath(args[1],winslash='/',mustWork=TRUE),.libPaths()))
ns <- asNamespace('stochtree')
stopifnot(!'hchs_rng' %in% names(getLoadedDLLs()))
vp <- get('.hchs_variance_parameters',ns)
fitfun <- get('bcf_linear_probit',ns)
kernel <- get('updateLinearTreatmentCpp_cpp_old',ns)
checks <- list()
check <- function(label,pass,value=NA_real_) {
 checks[[length(checks)+1L]] <<- data.frame(check=label,pass=isTRUE(pass),value=value)
 if(!isTRUE(pass)) stop('FAILED: ',label)
}
r<-c(.2,-.8,1.1,.4); b<-c(.8,-.3); bi<-.7; ls<-c(.4,.6,.2); tg<-.5
pp<-vp(r,b,bi,ls,tg,2.3,.8); v<-c(.1,.3,.9,2,5)
direct<-vapply(v,function(vv)sum(dnorm(r,0,sqrt(vv),log=TRUE))+sum(dnorm(c(b,bi),0,sqrt(vv)*c(ls[1:2],ls[3]*tg),log=TRUE))-(2.3+1)*log(vv)-.8/vv,numeric(1))
ig<--(pp$shape+1)*log(v)-pp$scale/v
err<-max(abs((direct-direct[1])-(ig-ig[1])))
check('Variance density-ratio identity',err<1e-10,err)
check('Counts all sigma-dependent coefficients',pp$coefficient_count==3L)
check('Uses configured prior shape',pp$shape==2.3+(4+3)/2)
check('Uses configured prior scale',abs(pp$scale-(.8+(sum(r^2)+sum((c(b,bi)/c(ls[1:2],ls[3]*tg))^2))/2))<1e-12)
p0<-vp(r,b,numeric(0),ls[1:2],tg,1,.2)
check('No interactions supported',p0$shape==4&&abs(p0$quadratic-sum((b/ls[1:2])^2))<1e-12)
check('No coefficients supported',vp(r,numeric(0),numeric(0),numeric(0),tg,1,.2)$shape==3)
bad<-list(list(local_scale=ls[-1]),list(global_scale=0),list(prior_shape=c(1,2)),list(prior_scale=numeric(0)),list(residual=c(NA,1)),list(local_scale=c(1,-1,1)))
base<-list(residual=r,beta=b,beta_int=bi,local_scale=ls,global_scale=tg,prior_shape=1,prior_scale=.001)
for(i in seq_along(bad)){a<-modifyList(base,bad[[i]]);check(paste('Invalid variance inputs',i),inherits(try(do.call(vp,a),silent=TRUE),'try-error'))}
set.seed(414);X<-matrix(rnorm(160),80,2);Z<-rep(c(-.5,.5),40);y<-sin(X[,1])+.5*Z+rnorm(80)
D<-Z*cbind(X,X[,1]*X[,2]);ka<-list(X_design=D,XtX_design=crossprod(D),X=X,Z=Z,propensity_train=rep(.5,80),residual=y,are_continuous=c(1L,1L),alpha=0,beta=c(0,0),beta_int=0,tau_beta=rep(1,3),nu=rep(1,3),xi=1,tau_int=1,sigma=1,alpha_prior_sd=10,tau_glob=1,sample_global_prior='hc-hs',unlink=TRUE,gibbs=TRUE,save_output=FALSE,index=1L,max_steps=50L,step_out=.5,propensity_seperate='none',regularize_ATE=FALSE,hn_scale=1)
set.seed(813);before<-.Random.seed;a<-do.call(kernel,ka);after<-.Random.seed;nexta<-runif(4)
check('Compiled kernel advances R RNG',!identical(before,after))
set.seed(813);aa<-do.call(kernel,ka);nextaa<-runif(4)
check('Compiled kernel replays under fixed R seed',identical(a,aa))
check('Following R draws replay',identical(nexta,nextaa))
aa<-do.call(kernel,ka)
check('Successive kernel calls differ',!identical(a$params,aa$params))
gp<-list(standardize=TRUE,sample_sigma2_global=TRUE,sigma2_global_shape=2.3,sigma2_global_scale=.8,propensity_covariate='none',adaptive_coding=FALSE,random_seed=826,num_chains=1,keep_burnin=FALSE,keep_gfr=FALSE,keep_every=1,verbose=FALSE,sample_global_prior='hc-hs',unlink=TRUE,gibbs=TRUE,hn_scale=1,propensity_seperate='none',interaction_rule='continuous',standardize_cov=FALSE,simple_prior=FALSE,regularize_ATE=FALSE,sigma_residual=0,use_ncp=FALSE,orthogonalize=FALSE,robust=FALSE,p0=0)
runfit<-function(g=gp,gfr=2)fitfun(X,Z,y,rep(.5,80),num_gfr=gfr,num_burnin=3,num_mcmc=8,general_params=g,prognostic_forest_params=list(num_trees=5))
set.seed(829);seed<-.Random.seed;fit<-runfit()
check('Function restores existing R RNG',identical(seed,.Random.seed))
check('Scope metadata eligible',isTRUE(fit$model_params$hchs_variance_scope))
check('Scope metadata names repaired conditional',identical(fit$model_params$variance_update,'hchs-full-conditional-20260927'))
check('Prior hyperparameter metadata',identical(fit$model_params$variance_prior_shape,2.3)&&identical(fit$model_params$variance_prior_scale,.8))
check('Finite retained coefficients',all(is.finite(c(fit$Alpha,fit$Beta,fit$Beta_int))))
fit2<-runfit();check('Whole sampler reproducibility',identical(fit$Beta,fit2$Beta)&&identical(fit$Beta_int,fit2$Beta_int)&&identical(fit$Alpha,fit2$Alpha))
g<-gp;g$sample_sigma2_global<-FALSE;g$sigma2_global_init<-1
fixed<-runfit(g)
check('Fixed variance bypass recorded',identical(fixed$model_params$variance_update,'fixed-variance')&&isTRUE(fixed$model_params$hchs_variance_scope))
g<-gp;g$sample_global_prior<-'none';g$gibbs<-FALSE
legacy<-runfit(g)
check('Unrepaired scope explicitly legacy',identical(legacy$model_params$variance_update,'legacy-unvalidated')&&!isTRUE(legacy$model_params$hchs_variance_scope))
g$simple_prior<-TRUE
simple<-runfit(g)
check('Simple-prior routing metadata names actual old kernel',identical(simple$model_params$linear_rng_scope,'old-kernel-R-RNG-scoped-20260927')&&identical(simple$model_params$variance_update,'legacy-unvalidated'))
g<-gp;g$control_coding_init<-'invalid';before<-.Random.seed
check('Post-seed error is raised',inherits(try(runfit(g),silent=TRUE),'try-error'))
check('RNG restored on error',identical(before,.Random.seed))
rm('.Random.seed',envir=.GlobalEnv);invisible(runfit());check('Absent RNG restored after success',!exists('.Random.seed',envir=.GlobalEnv,inherits=FALSE))
invisible(try(runfit(g),silent=TRUE));check('Absent RNG restored after error',!exists('.Random.seed',envir=.GlobalEnv,inherits=FALSE))
res<-do.call(rbind,checks);print(res,row.names=FALSE)
cat('CHECKS',nrow(res),'PASSED\nRuntime:',getLoadedDLLs()[['stochtree']][['path']],'\n')
if(length(args)>1)write.csv(res,args[2],row.names=FALSE)
